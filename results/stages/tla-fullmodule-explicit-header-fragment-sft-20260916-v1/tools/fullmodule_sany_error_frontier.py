"""Measure bounded, reference-free SANY repair frontiers for saved candidates.

This is a diagnostic, not a repairer or an acceptance scorer.  It applies only
pre-registered layout transformations to the exact saved generated bytes and
re-runs the pinned SANY process.  It never substitutes reference text, awards
model credit, or treats a counterfactual edited string as a model output.
"""

import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from harness.proof_ladder_check import classify_sany
from tools import protected_checkpoint_preflight as preflight
from tools.protected_paired_sany_score import JAR_SHA, score

ROWS = (47, 107)
PHASES = ("restored_parent", "trained_child")


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def dump(path, value):
    path.write_text(json.dumps(value, indent=2) + "\n")


def negative(reference):
    value = re.sub(r"(?m)^={4,}\s*$", "SyntaxNegativeControl == )\n====", reference)
    if value == reference:
        raise ValueError("negative control did not change reference")
    return value


def parenthesize_existential_branches(text):
    """Parenthesize only same-line `\\/ \\E ...` branch bodies."""
    changed = False
    lines = []
    for line in text.splitlines():
        marker = r"\/ \E "
        if marker in line and not line.rstrip().endswith(")"):
            at = line.index(marker)
            prefix = line[: at + len(r"\/")]
            body = line[at + len(r"\/ "):]
            line = prefix + " (" + body + ")"
            changed = True
        lines.append(line)
    return "\n".join(lines) + ("\n" if text.endswith("\n") else ""), changed


def add_missing_init_conjunction(text):
    """Probe the exact row-47 child omission without changing other lines."""
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if line.startswith("readSnapshots =") and index > 0:
            if not lines[index - 1].rstrip().endswith(("/\\", "\\/")):
                lines[index] = "       /\\ " + line
                return "\n".join(lines) + ("\n" if text.endswith("\n") else ""), True
            return text, False
    return text, False


def parenthesize_post_disjunction(text):
    old = ('post(b) == snapshot\' = snapshot \\/ snapshot\' = '
           '[snapshot EXCEPT![b] = "held"] /\\ holder\' = b')
    new = ('post(b) == (snapshot\' = snapshot \\/ snapshot\' = '
           '[snapshot EXCEPT![b] = "held"]) /\\ holder\' = b')
    if old not in text:
        return text, False
    return text.replace(old, new, 1), True


def close_incomplete_tail(text):
    """Close a visibly unterminated final line, without inventing its body."""
    lines = text.splitlines()
    if not lines or lines[-1].strip() == "====":
        return text, False
    if not lines[-1].rstrip().endswith('"'):
        return text, False
    # The generated child has no footer because its final string literal is
    # cut off.  Drop only that incomplete line and close the module skeleton.
    lines.pop()
    lines.extend(("", "Spec == Init /\\ [][Next]_vars", "", "===="))
    return "\n".join(lines) + "\n", True


def layout_repair(text):
    edits = []
    value, changed = add_missing_init_conjunction(text)
    if changed:
        edits.append("insert_missing_init_conjunction")
    value, changed = parenthesize_post_disjunction(value)
    if changed:
        edits.append("parenthesize_post_disjunction")
    value, changed = parenthesize_existential_branches(value)
    if changed:
        edits.append("parenthesize_existential_branches")
    return value, edits


def classify_variant(text, output, java, jar):
    result = score(text, output, java, jar)
    log = output / "sany.log"
    diagnostic = log.read_text() if log.exists() else ""
    result["first_error"] = next(
        (line.strip() for line in diagnostic.splitlines()
         if "Lexical error" in line or "Unknown operator" in line
         or "Precedence conflict" in line or "Was expecting" in line
         or "Encountered" in line),
        next((line.strip() for line in diagnostic.splitlines()
              if "Parse Error" in line or "Fatal errors" in line), None),
    )
    result["classified_status"] = classify_sany(
        result.get("returncode", 1), diagnostic, False, result.get("module_name"))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--receipt", type=Path, required=True)
    parser.add_argument("--packet", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    receipt = json.loads(args.receipt.read_bytes())
    packet = json.loads(args.packet.read_bytes())
    if receipt.get("complete") is not True or receipt.get("reload_tensors_exact") is not True:
        raise ValueError("complete exact-reload receipt required")
    if preflight.file_sha(args.packet) != preflight.PACKET_SHA:
        raise ValueError("frozen packet mismatch")
    selected = preflight.protected_rows(packet)
    if tuple(sorted(selected)) != ROWS:
        raise ValueError("exact protected rows required")

    java = shutil.which("java")
    jar = (ROOT / "tools/tla2tools.jar").resolve()
    if java is None or preflight.file_sha(jar) != JAR_SHA:
        raise ValueError("pinned SANY runtime unavailable")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    dump(output / "identity.json", dict(
        receipt_sha256=preflight.file_sha(args.receipt),
        packet_sha256=preflight.file_sha(args.packet),
        jar_sha256=JAR_SHA,
        source_sha256=preflight.file_sha(Path(__file__)),
        classifier_sha256=preflight.file_sha(ROOT / "harness/proof_ladder_check.py"),
        reference_free=True,
        edited_strings_are_diagnostic_only=True,
    ))

    controls = []
    for row in ROWS:
        reference = selected[row][0]["response"]
        controls.append(dict(row=row, label="reference", **classify_variant(
            reference, output / "controls" / f"{row}-reference", java, jar)))
        controls.append(dict(row=row, label="negative", **classify_variant(
            negative(reference), output / "controls" / f"{row}-negative", java, jar)))
    dump(output / "controls.json", controls)

    records = []
    record_dir = args.receipt.parent
    for phase in PHASES:
        for row in ROWS:
            saved = json.loads((record_dir / f"{phase}-row-{row}.json").read_bytes())
            raw = saved["raw_reply"]
            if sha(raw) != saved["raw_reply_sha256"]:
                raise ValueError(f"raw digest mismatch: {phase}/{row}")
            layout, edits = layout_repair(raw)
            closed, close_edits = close_incomplete_tail(raw)
            full, full_edits = close_incomplete_tail(layout)
            close_names = ["close_incomplete_tail"] if close_edits else []
            full_names = edits + close_names
            variants = (("original", raw, []),
                        ("layout", layout, edits),
                        ("close_tail", closed, close_names),
                        ("layout_close_tail", full, full_names))
            for name, candidate, applied in variants:
                variant_dir = output / "candidates" / f"{phase}-{row}" / name
                result = classify_variant(candidate, variant_dir, java, jar)
                scored = dict(result)
                score_candidate_sha256 = scored.pop("candidate_sha256", None)
                records.append(dict(
                    row=row, phase=phase, variant=name,
                    original_sha256=sha(raw), candidate_sha256=sha(candidate),
                    score_candidate_sha256=score_candidate_sha256,
                    edits=applied, **scored))
    dump(output / "rows.json", records)
    controls_ok = all(
        c["status"] == ("pass" if c["label"] == "reference" else "model_sany_reject")
        for c in controls)
    measured = all(r["status"] in ("pass", "model_sany_reject") for r in records)
    pass_by_variant = {}
    for r in records:
        pass_by_variant.setdefault(r["variant"], [0, 0])
        pass_by_variant[r["variant"]][0] += int(r["status"] == "pass")
        pass_by_variant[r["variant"]][1] += 1
    summary = dict(
        complete=controls_ok and measured,
        controls_ok=controls_ok,
        requested_candidates=len(records),
        measured_candidates=sum(r["status"] in ("pass", "model_sany_reject") for r in records),
        pass_by_variant=pass_by_variant,
        protected_rows=list(ROWS),
        interpretation=(
            "Counterfactual layout edits are diagnostic only. A passing edited string "
            "is not a model output and earns no protected, quality, gate or proof credit."
        ),
        model_improvement_claim=False,
        quality_claim=False,
        gate_claim=False,
        proof_claim=False,
        generalization_claim=False,
        tlc_claim=False,
        nonvacuity_claim=False,
    )
    dump(output / "summary.json", summary)
    print(json.dumps(summary, sort_keys=True))


if __name__ == "__main__":
    main()
